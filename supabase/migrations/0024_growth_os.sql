-- 0024_growth_os.sql
-- Founder Growth Command Center (/growth-os) persistence. Owner-only data: a
-- lightweight outreach CRM, campaigns, tracked links + click log, and early-user
-- feedback. Fully idempotent. RLS: a user can only ever touch their OWN rows;
-- the /growth-os route is additionally gated to ADMIN_EMAILS in the app.

-- ── Prospects (outreach CRM) ────────────────────────────────────────────────
create table if not exists public.growth_prospects (
  id            uuid primary key default gen_random_uuid(),
  owner_id      uuid not null references auth.users(id) on delete cascade,
  name          text not null,
  category      text,                       -- creator | community | newsletter | podcast | friend | partner | ...
  platform      text,
  audience_size integer,
  contact       text,
  relevance     integer,                    -- 1..5
  status        text not null default 'to_contact', -- to_contact | contacted | replied | activated | passed
  last_contact  date,
  next_follow_up date,
  message_used  text,
  response      text,
  attributed_signups integer not null default 0,
  activated_users    integer not null default 0,
  referred_users     integer not null default 0,
  notes         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_growth_prospects_owner on public.growth_prospects(owner_id, next_follow_up);
alter table public.growth_prospects enable row level security;
drop policy if exists growth_prospects_own on public.growth_prospects;
create policy growth_prospects_own on public.growth_prospects for all using (owner_id = auth.uid()) with check (owner_id = auth.uid());

-- ── Campaigns ───────────────────────────────────────────────────────────────
create table if not exists public.growth_campaigns (
  id            uuid primary key default gen_random_uuid(),
